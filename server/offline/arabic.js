const STRIP = /[ً-ٰٟ]/g; // short vowels, for matching only
const PLURAL_NO_FINAL_WAW = new Set(['نحو', 'نمو', 'نجو', 'نبو']); // real words ending in و after ن (نبو handled above)

/** Libyan past-tense endings: كملتو -> كملتم (you did), ساهمو -> ساهموا (they did). */
function pastFix(w) {
  if (/^[\u0621-\u064A]{2,}تو$/.test(w)) return `${w.slice(0, -2)}تم`;
  if (/^[^يتنأ][\u0621-\u064A]{2,}و$/.test(w) && !/^(ال|لل|وال|بال)/.test(w)) return `${w}ا`; // not nouns: الجو, العضو
  if (/^[يت][\u0621-\u064A]{2,}و$/.test(w)) return `${w}ن`; // يحاولو -> يحاولون
  return w;
}

function verbFix(w) {
  // Libyan first-person plural: نشكرو -> نشكر, نطورو -> نطور (MSA has no final و here)
  if (/^ن[ء-ي]{2,}و$/.test(w) && !PLURAL_NO_FINAL_WAW.has(w)) return w.slice(0, -1);
  return w;
}

/** Rewrite common Libyan Arabic into formal Arabic (for the offline translator; the screen keeps the real words). */
export function normalizeLibyan(text) {
  let s = String(text || '');
  for (const [re, rep] of PHRASES) s = s.replace(re, rep);
  // "كان تبو ..." at the start of a clause = "if you want ..." (كان + a "you" verb is the Libyan if)
  s = s.replace(/(^|[.!؟?،]\s*)كان (?=(تب[وي]|ت[\u0621-\u064A]{2,}و)(\s|$|[،.]))/g, '$1إذا ');
  // "كان فيه X، <do this>" = "if there is X, ..."
  s = s.replace(/(^|[.!؟?]\s*)كان فيه ([^،.!؟?]{1,40})،(?=\s*(ا[\u0621-\u064A]{2,}و|تفضلو))/g, '$1إذا كان هناك $2،');
  // هالملتقى -> هذا الملتقى, هالمرة / هالأيام -> هذه المرة / هذه الأيام
  s = s.replace(/(^|[\s،,.؟?!])هال(?=([ء-ي]{3,}))/g, (m, p1, w) => `${p1}${/(ة|ات)$/.test(w) || /^(أيام|ايام|ناس|مرة|سنة|فترة)/.test(w) ? 'هذه' : 'هذا'} ال`);
  const tokens = s.split(/(\s+|[،,.؟?!:؛;"'«»()])/);
  const words = tokens.map((t) => t.replace(STRIP, ''));
  const out = [];
  for (let i = 0; i < tokens.length; i += 1) {
    const raw = tokens[i];
    const w = words[i];
    if (!w || /^\s+$/.test(w) || /^[،,.؟?!:؛;"'«»()]$/.test(w)) { out.push(raw); continue; }
    const prev = words.slice(0, i).reverse().find((x) => x && !/^\s+$/.test(x));
    const next = words.slice(i + 1).find((x) => x && !/^\s+$/.test(x));
    // "قال اللي" = "said that"
    if ((w === 'اللي' || w === 'إللي') && prev && /^(قال|قالت|قالو|قالوا|يقول|تقول|نقول|يقولو)$/.test(prev)) { out.push('إن'); continue; }
    // "قاعد/قاعدة + verb" is the Libyan "-ing" (قاعدة تخدم = is working); otherwise قاعدة is a real word (rule, base).
    if (/^قاعد(ة|ين|ات)?$/.test(w) && next && /^[يتن]/.test(next)) continue;
    // "أما" after a comma means "but" in Libyan speech.
    if (w === 'أما' && prev === '،') { out.push('لكن'); continue; }
    // "ما ... ش" negation split over two words: ما يتعاودش -> لا يتكرر
    if (w === 'ما' && next && next.length > 3 && next.endsWith('ش')) { out.push(/^[يتنأ]/.test(next) ? 'لا' : 'ما'); continue; }
    if (prev === 'ما' && w.length > 3 && w.endsWith('ش')) { const v = verbFix(w.slice(0, -1)); out.push(v === 'يتعاود' ? 'يتكرر' : WORDS.get(v) || pastFix(v)); continue; }
    // ما...ش on one word: مانعرفش -> لا نعرف
    if (/^ما[ء-ي]{3,}ش$/.test(w) && !WORDS.has(w)) {
      let v = w.slice(2, -1);
      if (WORDS.has(v)) { out.push(`لا ${WORDS.get(v)}`); continue; }
      v = verbFix(v);
      if (/^ت[ء-ي]+او$/.test(v)) v = `${v.slice(0, -2)}وا`; // ماتنساوش -> لا تنسوا (don't forget)
      else if (/^ت[ء-ي]{2,}و$/.test(v)) v = `${v}ا`; // ماتمشوش -> لا تمشوا
      else if (/^ي[ء-ي]{2,}و$/.test(v)) v = `${v}ن`;
      out.push(`لا ${WORDS.get(v) || v}`);
      continue;
    }
    if (WORDS.has(w)) { const t = WORDS.get(w); if (t) out.push(t); else if (/^\s+$/.test(out.at(-1) || '')) out.pop(); continue; }
    // future بـ + known verb
    if (/^ب[نيت]/.test(w) && (FUTURE_VERBS.has(w.slice(1)) || /^ب[نيت][\u0621-\u064A]{2,}و$/.test(w) || (WORDS.has(w.slice(1)) && /^[نيت]/.test(WORDS.get(w.slice(1)))))) {
      const v = w.slice(1);
      const base = WORDS.get(v) || WORDS.get(verbFix(v)) || pastFix(verbFix(v));
      out.push(`س${base}`.replace(/^سسي/, 'سي'));
      continue;
    }
    // clitics: وتوا, والجاي... (و/ف + word)
    // future بـ + يتصلح (will be repaired)
    if (/^ب[يت]تصلح$/.test(w)) { out.push('سيتم إصلاحه'); continue; }
    const m = /^([وف])(.+)$/.exec(w);
    if (m && WORDS.has(m[2])) { out.push(`${m[1]}${WORDS.get(m[2])}`); continue; }
    const fixed = pastFix(verbFix(w));
    out.push(fixed === w ? raw : fixed);
  }
  let r = out.join('').replace(/الخاص بـ\s+/g, 'الخاص بـ');
  // "want / can" + verb needs أن in formal Arabic: نريد نشكر -> نريد أن نشكر
  r = r.replace(/(^|\s)(أريد|نريد|يريد|تريد|يريدون|تريدون|أستطيع|نستطيع|يستطيع|تستطيع|يستطيعون|نحاول|يحاول|تحاول|أحاول|يحاولون)\s+(?=[نيتأ][\u0621-\u064A]{2,})(?!أن\s)/g, '$1$2 أن ');
  // after أن / لكي / لن / حتى the verb loses its ن: أن تسألون -> أن تسألوا
  r = r.replace(/(^|\s)(أن|لكي|كي|لن|حتى)\s+([يت][\u0621-\u064A]{2,})ون(?=\s|$|[،.؟?!])/g, '$1$2 $3وا');
  return r.replace(/أن أن /g, 'أن ').replace(/\s{2,}/g, ' ').replace(/\s+([،.؟?!])/g, '$1').trim();
}
